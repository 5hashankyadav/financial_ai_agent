class FeedbackRequest(BaseModel):
    question: str = Field(..., description="The question that was asked")
    role: str = Field(default="CEO", description="Role of the user")
    rating: int = Field(..., description="+1 for positive, -1 for negative")
    route: str = Field(default="", description="Route taken")
    answer: str = Field(default="", description="Answer generated by agent")
    correction: str = Field(default="", description="Optional user correction")


@app.post("/feedback")
def submit_feedback(body: FeedbackRequest):
    from app.feedback import FeedbackStore
    store = FeedbackStore()
    entry = store.save_feedback(
        question=body.question,
        role=body.role,
        rating=body.rating,
        route=body.route,
        answer=body.answer,
        correction=body.correction,
    )
    return {
        "status": "success",
        "message": "Feedback recorded successfully",
        "entry": entry,
    }


@app.post(
    "/ask",
    response_model=AskResponse,
    summary="Ask a financial question",
    description=(
        "Analyze a financial question using "
        "structured financial data, retrieval-augmented "
        "generation, or a hybrid approach."
    ),
    responses={
        400: {
            "description": "Question cannot be empty.",
        },
        422: {
            "description": "Invalid request format.",
        },
    },
)
def ask(
    request: Request,
    body: AskRequest,
    agent: FinancialAgent = Depends(get_agent),
):

    question = body.question.strip()

    request_id = request.state.request_id

    if not question:

        logger.warning(
            "Empty question | request_id=%s",
            request_id,
        )

        raise HTTPException(
            status_code=400,
            detail="Question cannot be empty.",
        )

    try:
        role = normalize_role(body.role)

    except ValueError:

        logger.warning(
            "Invalid role | request_id=%s | role=%s",
            request_id,
            body.role,
        )

        raise HTTPException(
            status_code=400,
            detail=(
                "Invalid role. Allowed roles: "
                "CEO, CTO, ANALYST."
            ),
        )

    logger.info(
        "Received question | request_id=%s | "
        "role=%s | question=%s",
        request_id,
        role.value,
        question,
    )

    try:

        result = agent.ask(
            question,
            role=role.value,
        )

        logger.info(
            "Question classified | request_id=%s | "
            "role=%s | route=%s",
            request_id,
            role.value,
            result["route"],
        )

        return {
            "question": question,
            "route": result["route"],
            "answer": result["answer"],
            "sources": result.get(
                "sources",
                [],
            ),
        }

    except Exception as exc:

        logger.exception(
            "Error while processing question | "
            "request_id=%s | error=%s",
            request_id,
            exc,
        )

        raise AgentProcessingError(
            "Failed to process financial question."
        ) from exc



class AgentProcessingError(Exception):
    """Raised when the financial agent cannot process a request."""


app = FastAPI(
    title="Financial AI Agent",
    description="AI-powered financial analysis and RAG API",
    version="1.0.0",
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=False,
    allow_methods=["*"],
    allow_headers=["*"],
)



@app.middleware("http")
async def add_request_id(request: Request, call_next):

    request_id = str(uuid.uuid4())

    request.state.request_id = request_id

    start_time = time.perf_counter()

    logger.info(
        "Request started | request_id=%s | method=%s | path=%s",
        request_id,
        request.method,
        request.url.path,
    )

    response = await call_next(request)

    duration_ms = (
        time.perf_counter() - start_time
    ) * 1000

    response.headers["X-Request-ID"] = request_id

    logger.info(
        "Request completed | request_id=%s | "
        "status=%s | duration_ms=%.2f",
        request_id,
        response.status_code,
        duration_ms,
    )

    return response


@app.exception_handler(AgentProcessingError)
async def agent_processing_error_handler(
    request: Request,
    exc: AgentProcessingError,
):

    request_id = getattr(
        request.state,
        "request_id",
        "unknown",
    )

    logger.error(
        "Financial agent processing error | "
        "request_id=%s | error=%s",
        request_id,
        exc,
    )

    return JSONResponse(
        status_code=500,
        content={
            "detail": (
                "An internal error occurred while "
                "processing the question."
            )
        },
    )


@lru_cache
def get_agent():
    """
    Create one shared FinancialAgent instance.
    """

    return FinancialAgent()


class AskRequest(BaseModel):

    question: str = Field(
        ...,
        description="Financial question to analyze.",
    )

    role: str = Field(
        default="CEO",
        description=(
            "User role used for data access control."
        ),
    )


class Source(BaseModel):

    source_file: str

    source_sheet: str | None = None

    source_row: int | None = None


class AskResponse(BaseModel):

    question: str = Field(
        ...,
        description="The original question",
    )

    route: str = Field(
        ...,
        description="The route taken to answer the question",
    )

    answer: str = Field(
        ...,
        description="The answer to the question",
    )

    sources: list[Source] = Field(
        ...,
        description="Sources used to generate the answer",
    )


